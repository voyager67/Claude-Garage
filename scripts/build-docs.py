#!/usr/bin/env python3
"""Generate docs/commands.md, docs/agents.md and the interactive site docs/index.html
from the frontmatter of agents/ and skills/. Run after adding or editing a command or agent."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PHASES = {
    "Setup": ["garage-init", "rules", "guide"],
    "Understand": ["recon", "patterns", "brainstorm"],
    "Plan": ["pitch", "blueprint", "preflight"],
    "Build": ["sprint", "test", "tidy"],
    "Verify": ["break", "audit"],
    "Ship": ["pr", "launch", "docs"],
    "Maintain": ["firefight", "retro", "standup"],
}
ICONS = {
    "scout": "🔭", "pm": "🎯", "architect": "📐", "builder": "🔨", "gremlin": "👹", "sentinel": "🛡️",
    "critic": "🧐", "detective": "🕵️", "scribe": "✍️", "chief": "🧭", "pixel": "🎨", "rigger": "🏗️", "tester": "🧪",
}
SITE_URL = "https://github.com/YOUR_GITHUB_USERNAME/claude-garage"


def fm(path):
    text = path.read_text(encoding="utf-8")
    end = text.find("\n---", 4)
    data = {}
    for line in text[4:end].splitlines():
        if ":" in line:
            k, _, v = line.partition(":")
            data[k.strip()] = v.strip().strip('"')
    return data


skills = {p.parent.name: fm(p) for p in sorted((ROOT / "skills").glob("*/SKILL.md"))}
agents = {p.stem: fm(p) for p in sorted((ROOT / "agents").glob("*.md"))}
phase_of = {c: ph for ph, cs in PHASES.items() for c in cs}
missing = sorted(set(skills) - set(phase_of))
if missing:
    raise SystemExit(f"Add these commands to PHASES in scripts/build-docs.py: {missing}")

# ---- commands.md
lines = ["# Command reference", "", "_Generated by `scripts/build-docs.py`. Commands are namespaced `/garage:<name>` when installed as a plugin and `/<name>` with the standalone installer._", ""]
for ph, cs in PHASES.items():
    lines += [f"## {ph}", "", "| Command | What it does | Argument |", "|---|---|---|"]
    for c in cs:
        s = skills[c]
        lines.append(f"| `/garage:{c}` | {s.get('description','')} | `{s.get('argument-hint','')}` |")
    lines.append("")
(ROOT / "docs" / "commands.md").write_text("\n".join(lines), encoding="utf-8")

# ---- agents.md
lines = ["# Agent reference", "", "_Generated by `scripts/build-docs.py`._", "", "| Agent | Job | Tools |", "|---|---|---|"]
for a, d in agents.items():
    lines.append(f"| {ICONS.get(a,'')} **{a}** | {d.get('description','')} | `{d.get('tools','')}` |")
(ROOT / "docs" / "agents.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

# ---- site
data = {
    "phases": PHASES,
    "commands": {c: {"d": s.get("description", ""), "a": s.get("argument-hint", "")} for c, s in skills.items()},
    "agents": {a: {"d": d.get("description", ""), "t": d.get("tools", ""), "i": ICONS.get(a, "")} for a, d in agents.items()},
    "repo": SITE_URL,
}
template = (ROOT / "scripts" / "site-template.html").read_text(encoding="utf-8")
html = template.replace("/*__DATA__*/null", json.dumps(data, ensure_ascii=False)).replace("__NCMD__", str(len(skills))).replace("__NAGT__", str(len(agents)))
(ROOT / "docs" / "index.html").write_text(html, encoding="utf-8")
print(f"Built docs: {len(skills)} commands, {len(agents)} agents.")
